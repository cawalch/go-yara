"""Build the playground against the same release as the documentation."""
import hashlib
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import tarfile

SOURCE = Path(__file__).resolve().parent
SITE = SOURCE.parent


def leb(value):
    output = bytearray()
    while value > 127:
        output.append((value & 127) | 128)
        value >>= 7
    output.append(value)
    return bytes(output)


def read_leb(data, offset):
    value = 0
    for shift in range(0, 35, 7):
        byte = data[offset]
        offset += 1
        value |= (byte & 127) << shift
        if byte < 128:
            return value, offset
    raise ValueError('Invalid Wasm unsigned LEB128')


def cap_memory(data, maximum):
    # Go currently emits an unbounded, defined memory. Change only its limits,
    # preserving every other section. Refuse unfamiliar layouts/toolchain changes.
    if data[:8] != b'\0asm\x01\0\0\0' or maximum % 65536:
        raise ValueError('Expected Wasm v1 and whole memory pages')
    output, offset, found = bytearray(data[:8]), 8, False
    while offset < len(data):
        kind = data[offset]
        length, start = read_leb(data, offset + 1)
        end = start + length
        if end > len(data):
            raise ValueError('Truncated Wasm section')
        payload = data[start:end]
        if kind == 5:
            count, cursor = read_leb(payload, 0)
            flags, cursor = read_leb(payload, cursor)
            initial, cursor = read_leb(payload, cursor)
            if found or count != 1 or flags != 0 or cursor != len(payload) or initial > maximum // 65536:
                raise ValueError('Unexpected memory layout; review the memory cap')
            payload = leb(1) + leb(1) + leb(initial) + leb(maximum // 65536)
            found = True
        output += bytes([kind]) + leb(len(payload)) + payload
        offset = end
    if not found:
        raise ValueError('No defined memory; cannot enforce the limit')
    return bytes(output)


def build():
    release = json.loads((SITE / 'src/generated/release.json').read_text())['version']
    if not re.fullmatch(r'v\d+\.\d+\.\d+', release):
        raise ValueError('Expected a stable documentation release')
    limits = json.loads((SOURCE / 'engine/limits.json').read_text())
    env = {**os.environ, 'GOWORK': 'off', 'GOEXPERIMENT': '', 'CGO_ENABLED': '0'}
    with tempfile.TemporaryDirectory(prefix='go-yara-playground-') as directory:
        temp = Path(directory)
        archive = subprocess.check_output(['git', 'archive', release], cwd=SITE.parent)
        with tarfile.open(fileobj=io.BytesIO(archive)) as files:
            files.extractall(temp, filter='data')
        bridge = temp / 'site/playground'
        bridge.mkdir(parents=True, exist_ok=True)
        for name in ['engine', 'browser', 'tests']:
            if (bridge / name).exists():
                shutil.rmtree(bridge / name)
            shutil.copytree(SOURCE / name, bridge / name)
        # Overlay only the current bridge onto released library sources. This
        # also avoids ambiguous nested-module imports once a release includes it.
        subprocess.run(['go', 'test', './site/playground/engine'], cwd=temp, env=env, check=True)
        subprocess.run(['go', 'build', '-trimpath', '-ldflags=-s -w', '-o', str(temp / 'scanner.wasm'), './site/playground/browser'], cwd=temp, env={**env, 'GOOS': 'js', 'GOARCH': 'wasm'}, check=True)
        goroot = Path(subprocess.check_output(['go', 'env', 'GOROOT'], cwd=temp, env=env, text=True).strip())
        go_version = subprocess.check_output(['go', 'version'], cwd=temp, env=env, text=True).strip()
        wasm = cap_memory((temp / 'scanner.wasm').read_bytes(), limits['memoryBytes'])
    shim = (goroot / 'lib/wasm/wasm_exec.js').read_bytes()
    config = {'version': release, 'limits': limits}
    worker = (SOURCE / 'worker.js').read_text().replace('__CONFIG__', json.dumps(config)).encode()
    identity = hashlib.sha256(wasm + shim + worker).hexdigest()[:20]
    public = SITE / 'public/playground'
    # This directory is exclusively generated by this builder.
    if public.exists():
        shutil.rmtree(public)
    target = public / identity
    target.mkdir(parents=True)
    for name, data in [('scanner.wasm', wasm), ('wasm_exec.js', shim), ('worker.js', worker)]:
        (target / name).write_bytes(data)
    metadata = {**config, 'id': identity, 'wasmBytes': len(wasm), 'sha256': hashlib.sha256(wasm).hexdigest(), 'go': go_version, 'workerURL': f'/go-yara/playground/{identity}/worker.js'}
    (target / 'manifest.json').write_text(json.dumps(metadata, indent=2) + '\n')
    (SITE / 'src/generated/playground.json').write_text(json.dumps(metadata, indent=2) + '\n')
    print(f'Built {release} playground: {len(wasm):,} bytes, {limits["memoryBytes"] // 1048576} MiB hard linear-memory limit, {identity}')


if __name__ == '__main__':
    build()
